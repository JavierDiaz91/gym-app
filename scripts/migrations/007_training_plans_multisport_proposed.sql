-- Kivra: multi-sport training plans, migration 001 (PROPOSED; NOT EXECUTED)
-- Additive: preserves routines, member_routines, routine_exercises and exercises.
-- Requires PostgreSQL; review on Neon before execution.
BEGIN;

CREATE TABLE IF NOT EXISTS training_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_id INTEGER REFERENCES gyms(id) ON DELETE CASCADE,
  dimension TEXT NOT NULL CHECK (dimension IN ('discipline','objective','level','audience')),
  slug TEXT NOT NULL CHECK (length(trim(slug)) > 0),
  label TEXT NOT NULL CHECK (length(trim(label)) > 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_training_categories_global
  ON training_categories (dimension, slug) WHERE gym_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_training_categories_gym
  ON training_categories (gym_id, dimension, slug) WHERE gym_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS training_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_id INTEGER NOT NULL REFERENCES gyms(id),
  trainer_id INTEGER NOT NULL REFERENCES trainers(id),
  title TEXT NOT NULL CHECK (length(trim(title)) > 0),
  description TEXT,
  duration_weeks INTEGER NOT NULL DEFAULT 4 CHECK (duration_weeks BETWEEN 1 AND 52),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
  source_plan_id BIGINT REFERENCES training_plans(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (id, gym_id)
);
CREATE INDEX IF NOT EXISTS ix_training_plans_gym_trainer ON training_plans(gym_id,trainer_id);

CREATE TABLE IF NOT EXISTS training_plan_categories (
  plan_id BIGINT NOT NULL REFERENCES training_plans(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES training_categories(id),
  PRIMARY KEY(plan_id,category_id)
);

CREATE TABLE IF NOT EXISTS training_plan_days (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id BIGINT NOT NULL REFERENCES training_plans(id) ON DELETE CASCADE,
  day_index INTEGER NOT NULL CHECK(day_index BETWEEN 1 AND 7),
  title TEXT NOT NULL,
  modality TEXT NOT NULL CHECK(modality IN ('strength','running','mixed','mobility','other')),
  sort_order INTEGER NOT NULL DEFAULT 0,
  UNIQUE(plan_id,day_index)
);

CREATE TABLE IF NOT EXISTS training_plan_blocks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day_id BIGINT NOT NULL REFERENCES training_plan_days(id) ON DELETE CASCADE,
  block_type TEXT NOT NULL CHECK(block_type IN ('warmup','main','circuit','cooldown','custom')),
  title TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS training_media_assets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_id INTEGER NOT NULL REFERENCES gyms(id),
  uploader_user_id INTEGER NOT NULL REFERENCES users(id),
  storage_key TEXT NOT NULL UNIQUE,
  mime_type TEXT NOT NULL CHECK(mime_type IN ('image/jpeg','image/png','image/webp')),
  size_bytes BIGINT NOT NULL CHECK(size_bytes > 0 AND size_bytes <= 10485760),
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','ready','deleted')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS training_plan_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  block_id BIGINT NOT NULL REFERENCES training_plan_blocks(id) ON DELETE CASCADE,
  exercise_id INTEGER REFERENCES exercises(id),
  media_asset_id BIGINT REFERENCES training_media_assets(id),
  item_type TEXT NOT NULL CHECK(item_type IN ('exercise','run_interval','timed_activity')),
  title_snapshot TEXT NOT NULL,
  instructions TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS training_week_prescriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES training_plan_items(id) ON DELETE CASCADE,
  week_number INTEGER NOT NULL CHECK(week_number BETWEEN 1 AND 52),
  sets INTEGER CHECK(sets > 0),
  reps_text TEXT,
  rir_text TEXT,
  rest_seconds INTEGER CHECK(rest_seconds >= 0),
  tempo_text TEXT,
  load_text TEXT,
  distance_meters INTEGER CHECK(distance_meters >= 0),
  duration_seconds INTEGER CHECK(duration_seconds >= 0),
  pace_text TEXT,
  interval_work_seconds INTEGER CHECK(interval_work_seconds >= 0),
  interval_rest_seconds INTEGER CHECK(interval_rest_seconds >= 0),
  notes TEXT,
  UNIQUE(item_id,week_number)
);

CREATE TABLE IF NOT EXISTS member_training_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_id INTEGER NOT NULL REFERENCES gyms(id),
  member_id INTEGER NOT NULL REFERENCES members(id),
  trainer_id INTEGER NOT NULL REFERENCES trainers(id),
  source_plan_id BIGINT REFERENCES training_plans(id) ON DELETE SET NULL,
  source_version INTEGER NOT NULL CHECK(source_version > 0),
  start_date DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('scheduled','active','completed','cancelled')),
  snapshot_jsonb JSONB NOT NULL CHECK(jsonb_typeof(snapshot_jsonb) = 'object'),
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(id,member_id)
);
CREATE INDEX IF NOT EXISTS ix_member_training_plans_member ON member_training_plans(gym_id,member_id,status);

CREATE TABLE IF NOT EXISTS workout_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_training_plan_id BIGINT NOT NULL,
  member_id INTEGER NOT NULL,
  day_index INTEGER NOT NULL CHECK(day_index BETWEEN 1 AND 7),
  week_number INTEGER NOT NULL CHECK(week_number BETWEEN 1 AND 52),
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finished_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'in_progress' CHECK(status IN ('in_progress','completed','cancelled')),
  FOREIGN KEY(member_training_plan_id,member_id)
    REFERENCES member_training_plans(id,member_id)
);

CREATE TABLE IF NOT EXISTS workout_set_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workout_session_id BIGINT NOT NULL REFERENCES workout_sessions(id) ON DELETE CASCADE,
  item_snapshot_key TEXT NOT NULL,
  set_index INTEGER NOT NULL CHECK(set_index > 0),
  actual_reps INTEGER CHECK(actual_reps >= 0),
  actual_load NUMERIC(10,2) CHECK(actual_load >= 0),
  actual_rir NUMERIC(4,1) CHECK(actual_rir >= 0),
  duration_seconds INTEGER CHECK(duration_seconds >= 0),
  distance_meters INTEGER CHECK(distance_meters >= 0),
  notes TEXT,
  UNIQUE(workout_session_id,item_snapshot_key,set_index)
);

-- Multi-tenant consistency (same gym for plan/trainer/member, category scope,
-- media ownership) must be enforced in application services and preferably
-- DB triggers or composite FKs before production. No RLS assumed here.
-- Published plan immutability and week_number <= duration_weeks are also
-- service-level requirements pending implementation.
COMMIT;
