-- Solicitudes de membresía iniciadas por alumnos. No conceden acceso ni crean pagos.
CREATE TABLE IF NOT EXISTS public.member_plan_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_id integer NOT NULL,
  member_id integer NOT NULL,
  plan_id integer NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  CONSTRAINT member_plan_requests_member_fk FOREIGN KEY (member_id) REFERENCES public.members(id),
  CONSTRAINT member_plan_requests_plan_fk FOREIGN KEY (plan_id) REFERENCES public.membership_plans(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS member_plan_requests_one_pending
ON public.member_plan_requests (member_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS member_plan_requests_gym_status
ON public.member_plan_requests (gym_id, status, created_at DESC);
